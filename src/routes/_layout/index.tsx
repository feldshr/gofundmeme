import { Container, Skeleton } from "@mantine/core";
import { createFileRoute } from "@tanstack/react-router";
import {
  getGfmUsdRateOptions,
  getSolUsdRateOptions,
} from "../../query/queryOptions";

export interface StakingSearch {
  ref?: string;
  amount?: number;
}

export const Route = createFileRoute("/_layout/")({
  validateSearch: (search: Record<string, unknown>): StakingSearch => {
    return {
      ref: typeof search.ref === "string" ? search.ref : undefined,
      amount:
        typeof search.amount === "number"
          ? search.amount
          : typeof search.amount === "string" && !isNaN(Number(search.amount))
            ? Number(search.amount)
            : undefined,
    };
  },
  loader: async ({ context: { queryClient } }) => {
    await Promise.allSettled([
      queryClient.ensureQueryData(getGfmUsdRateOptions()),
      queryClient.ensureQueryData(getSolUsdRateOptions()),
    ]);
  },
  pendingComponent: IndexPending,
  head: () => ({
    meta: [
      { title: "$GFM Staking | GoFundMeme" },
      {
        name: "description",
        content:
          "Earn your share of all fees generated by the GoFundMeme protocol",
      },
      {
        property: "og:title",
        content: "$GFM Staking | GoFundMeme",
      },
      {
        property: "og:description",
        content:
          "Earn your share of all fees generated by the GoFundMeme protocol",
      },
      {
        property: "og:type",
        content: "website",
      },
      {
        name: "twitter:card",
        content: "summary_large_image",
      },
      {
        name: "twitter:title",
        content: "$GFM Staking | GoFundMeme",
      },
      {
        name: "twitter:description",
        content:
          "Earn your share of all fees generated by the GoFundMeme protocol",
      },
    ],
  }),
});

function IndexPending() {
  return (
    <Container
      size="md"
      my="md"
      px={{
        xs: "md",
        sm: "xl",
      }}
    >
      <Skeleton height={32} width={200} mb="xs" radius="sm" />
      <Skeleton height={18} width={240} mb="md" radius="sm" />
      <Skeleton height={260} radius="md" mb="md" />
      <Skeleton height={200} radius="md" />
    </Container>
  );
}
